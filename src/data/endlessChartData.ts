// Exact pitch transcription from voices-majin.ogg & voices-bf.ogg (in A minor, 155 BPM)
function getExactEndlessVocalMidi(tMs: number, d: number): number {
  const isPlayer = d < 4;
  const lane = d % 4;

  // Normalize player repetition timestamps to match Majin's lead phrases
  // Section 1: Majin 0..13160ms, BF 13161..25500ms (offset ~13354.8ms)
  if (tMs < 25500) {
    const rel = isPlayer ? tMs - 13354.8 : tMs;
    if (rel < 500) return 69; // A4 (with G-G#-A scoop)
    if (rel < 700) return 64; // E4
    if (rel < 1200) return 69; // A4
    if (rel < 1450) return 71; // B4
    if (rel < 1650) return 72; // C5
    if (rel < 1900) return 71; // B4
    if (rel < 2060) return 69; // A4
    if (rel < 2400) return 68; // G#4
    if (rel < 2600) return 74; // D5
    if (rel < 2800) return 72; // C5
    if (rel < 3000) return 71; // B4
    if (rel < 3120) return 72; // C5
    if (rel < 3220) return 77; // F5
    if (rel < 3400) return 76; // E5
    if (rel < 3600) return 74; // D5
    if (rel < 3800) return 72; // C5
    if (rel < 4150) return 71; // B4
    if (rel < 4300) return 69; // A4
    if (rel < 4400) return 68; // G#4
    if (rel < 4750) return 64; // E4
    if (rel < 4950) return 71; // B4
    if (rel < 5300) return 72; // C5
    if (rel < 6000) return 69; // A4
    if (rel < 6400) return 64; // E4
    if (rel < 6700) return 69; // A4
    if (rel < 6820) return 71; // B4
    if (rel < 6920) return 72; // C5
    if (rel < 7400) return 74; // D5
    if (rel < 7650) return 76; // E5
    if (rel < 7850) return 74; // D5
    if (rel < 8100) return 76; // E5
    if (rel < 8600) return 72; // C5
    if (rel < 8760) return 71; // B4
    if (rel < 8840) return 72; // C5
    if (rel < 8890) return 71; // B4
    if (rel < 9150) return 68; // G#4
    if (rel < 9550) return 72; // C5
    if (rel < 9800) return 71; // B4
    if (rel < 9980) return 68; // G#4
    if (rel < 10700) return 71; // B4
    if (rel < 11100) return 69; // A4
    if (rel < 11500) return 72; // C5
    if (rel < 12200) return 71; // B4
    const endMap = [69, 71, 74, 76];
    return endMap[lane];
  }

  // Section 2: Majin 25548..37838ms, BF 37935..50225ms (offset ~12387.1ms)
  if (tMs >= 25500 && tMs < 50280) {
    const rel = isPlayer ? tMs - 37935.5 : tMs - 25548.4;
    if (rel < 2500) {
      // Staccato A4 - C5 alternating motif
      return lane >= 2 ? 72 : 69;
    }
    if (rel < 4600) {
      const stepPitches = [69, 71, 67, 69, 65, 64, 65, 64, 67, 69, 65, 69];
      const idx = Math.floor(((rel - 2500) / 2100) * stepPitches.length);
      return stepPitches[Math.min(stepPitches.length - 1, Math.max(0, idx))];
    }
    if (rel < 7500) {
      const highPitches = [71, 72, 71, 67, 71, 77, 76, 74, 72, 71];
      const idx = Math.floor(((rel - 4600) / 2900) * highPitches.length);
      return highPitches[Math.min(highPitches.length - 1, Math.max(0, idx))];
    }
    if (rel < 10200) {
      return lane === 3 ? 79 : lane === 2 ? 76 : lane === 1 ? 74 : 72; // G5 / E5 / D5 / C5
    }
    const tailRun = [76, 74, 72, 71, 72, 74, 72, 71, 67];
    const idx = Math.floor(((rel - 10200) / 2200) * tailRun.length);
    return tailRun[Math.min(tailRun.length - 1, Math.max(0, idx))];
  }

  // Section 3: Majin 50322..56400ms, BF 56516..61100ms
  if (tMs >= 50280 && tMs < 61150) {
    const rel = isPlayer ? tMs - 56516.0 : tMs - 50322.6;
    if (rel < 1550) {
      // Fast descending 4-note arpeggio runs: C5-B4-A4-E4 then D5-C5-B4-G4
      const group = rel < 780 ? [64, 69, 71, 72] : [67, 71, 72, 74];
      return group[lane];
    }
    const mel = [79, 77, 76, 74, 72, 71, 67, 71, 72, 79, 76, 74, 72, 71];
    const idx = Math.floor(((rel - 1550) / 4200) * mel.length);
    return mel[Math.min(mel.length - 1, Math.max(0, idx))];
  }

  // Section 4: Duet Legato Harmony (61161..87000ms)
  if (tMs >= 61150 && tMs < 87200) {
    const cycle = (tMs - 61161) % 12387;
    let leadPitch = 69;
    if (cycle < 1500) leadPitch = 69; // A4
    else if (cycle < 2300) leadPitch = 71; // B4
    else if (cycle < 3100) leadPitch = 74; // D5
    else if (cycle < 3800) leadPitch = 72; // C5
    else if (cycle < 4600) leadPitch = 71; // B4
    else if (cycle < 6100) leadPitch = 64; // E4
    else if (cycle < 7600) leadPitch = [67, 69, 67, 64][lane];
    else if (cycle < 9200) leadPitch = [71, 76, 79, 76][lane]; // B4, E5, G5, E5
    else leadPitch = [71, 72, 74, 76][lane];

    // In the duet section, BF harmonizes a 3rd below Majin's soaring lead
    return isPlayer ? leadPitch - 3 : leadPitch;
  }

  // Section 5 (87483..112200ms) & Section 7 (137032..162000ms): Fast Chiptune Arpeggio Sections!
  if ((tMs >= 87200 && tMs < 112200) || tMs >= 137000) {
    const baseStart = tMs >= 137000 ? 137032.3 : 87483.9;
    const barPos = ((tMs - baseStart) % 6193.5) / 6193.5; // 4-bar chord cycle
    let chord: number[];
    if (barPos < 0.25) {
      chord = [69, 72, 76, 81]; // A minor (A4, C5, E5, A5)
    } else if (barPos < 0.5) {
      chord = [68, 71, 76, 80]; // E major (G#4, B4, E5, G#5)
    } else if (barPos < 0.75) {
      chord = [67, 72, 76, 79]; // C/G (G4, C5, E5, G5)
    } else {
      chord = [66, 71, 74, 78]; // Bm/F# (F#4, B4, D5, F#5)
    }
    const noteMidi = chord[lane];
    return isPlayer ? noteMidi - 5 : noteMidi;
  }

  // Section 6: Brass Call-and-Response (Majin 112258..124600ms, BF 124645..137000ms)
  const rel6 = isPlayer ? tMs - 124645.2 : tMs - 112258.1;
  if (rel6 < 3000) {
    const opening = [69, 69, 71, 72, 69, 64, 69, 64, 60, 59, 60, 55, 59, 55];
    const idx = Math.floor((rel6 / 3000) * opening.length);
    return opening[Math.min(opening.length - 1, Math.max(0, idx))];
  }
  if (rel6 < 6200) {
    const mid = [57, 59, 62, 60, 57, 64, 69, 71, 72, 74, 76, 72, 69];
    const idx = Math.floor(((rel6 - 3000) / 3200) * mid.length);
    return mid[Math.min(mid.length - 1, Math.max(0, idx))];
  }
  const secondHalf = [69, 69, 69, 67, 67, 67, 64, 62, 60, 59, 60, 57, 60, 67, 65, 64, 62, 60, 69, 71, 72, 74];
  const idx = Math.floor(((rel6 - 6200) / 6200) * secondHalf.length);
  return secondHalf[Math.min(secondHalf.length - 1, Math.max(0, idx))];
}

export function buildExactEndlessChart(songId: 'endless' | 'endless-og'): {
  notes: ChartNote[];
  events: SongEvent[];
} {
  const notes: ChartNote[] = ENDLESS_VSLICE_NOTES_TUPLE.map(
    ([t, d, l], index) => {
      // In V-Slice format: d = 0..3 is Player (Boyfriend), d = 4..7 is Opponent (Majin)
      const isPlayer = d < 4;
      const lane = (d % 4) as Direction;
      const pitchMidi = getExactEndlessVocalMidi(t, d);

      return {
        id: `${songId}-vslice-${index}`,
        timeMs: Math.round(t),
        lane,
        isPlayer,
        sustainMs: Math.round(l || 0),
        special: 'normal',
        pitchMidi,
      };
    }
  );

  const rawEvents =
    songId === 'endless' ? ENDLESS_VSLICE_EVENTS : ENDLESS_OG_VSLICE_EVENTS;

  const events: SongEvent[] = rawEvents.map((ev) => {
    if (ev.e === 'Strumline Spin') {
      return {
        timeMs: Math.round(ev.t),
        type: 'strumline_spin',
        value: '350',
      };
    }
    if (ev.e === 'FocusCamera') {
      return {
        timeMs: Math.round(ev.t),
        type: 'focus_camera',
        value: String(ev.v.char ?? 0),
      };
    }
    if (ev.e === 'ZoomCamera') {
      return {
        timeMs: Math.round(ev.t),
        type: 'zoom_camera',
        value: String(ev.v.zoom ?? 1),
      };
    }
    if (ev.e === 'NoteSwapEvent') {
      return {
        timeMs: Math.round(ev.t),
        type: 'noteskin_swap',
        value: String(ev.v.notestyle ?? 'majin'),
      };
    }
    if (ev.e === 'MajinCountdown') {
      return {
        timeMs: Math.round(ev.t),
        type: 'majin_countdown',
        value: String(ev.v.text ?? ''),
      };
    }
    return {
      timeMs: Math.round(ev.t),
      type: 'camera_bop',
      value: String(ev.v.intensity ?? 1.115),
    };
  });

  // Apply subtitle (00:00:24,179 --> 00:00:25,789: "The fun never ends!") exclusively to 'endless' (NOT 'endless-og')
  if (songId === 'endless') {
    events.push(
      { timeMs: 24179, type: 'lyrics', value: 'The fun never ends!' },
      { timeMs: 25789, type: 'lyrics', value: '' }
    );
    events.sort((a, b) => a.timeMs - b.timeMs);
  }

  return { notes, events };
}
