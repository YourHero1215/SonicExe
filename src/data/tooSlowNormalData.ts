export function buildTooSlowNormalChart(): {
  notes: ChartNote[];
  events: SongEvent[];
} {
  const notes: ChartNote[] = TOO_SLOW_NORMAL_NOTES.map(
    ([t, d, l, isStatic], idx) => {
      const isPlayer = d < 4;
      const lane = (d % 4) as Direction;

      // Section-accurate E minor / chromatic descending intro & Phrygian drop pitches
      let baseMidi = 52;
      if (t < 28440) {
        // 0..28.44s: Chromatic descending piano intro progression
        const barIdx = Math.floor(t / 1777.7) % 8;
        const rootWalk = [52, 51, 50, 49, 48, 47, 45, 44][barIdx];
        const intervals = [0, 3, 7, 12];
        baseMidi = rootWalk + intervals[lane] + (isPlayer ? 12 : 0);
      } else {
        const dropScale = [52, 55, 57, 58, 59, 62, 64, 67];
        const laneOffset = lane === 0 ? 0 : lane === 1 ? 2 : lane === 2 ? 4 : 6;
        baseMidi =
          dropScale[(laneOffset + (idx % 4)) % dropScale.length] +
          (isPlayer ? 12 : -5);
      }

      return {
        id: `too-slow-vslice-${idx}`,
        timeMs: t,
        lane,
        isPlayer,
        sustainMs: l || 0,
        special: isStatic ? 'static' : 'normal',
        pitchMidi: baseMidi,
      };
    }
  );

  return {
    notes,
    events: TOO_SLOW_NORMAL_EVENTS.map((e) => ({ ...e })),
  };
}
